#!/usr/bin/env node
// usage: node tools/widget_cli.js check <file.json...>
//        node tools/widget_cli.js bin <outdir> <file.json...>
const fs = require('fs'), path = require('path');
const W = require('../app/widgetlib.js');
const [cmd, ...rest] = process.argv.slice(2);
let bad = 0;
if (cmd === 'check') {
  for (const f of rest) { const e = W.validateFile(JSON.parse(fs.readFileSync(f, 'utf8'))); if (e.length) { bad++; console.log('FAIL', f, e.join('; ')); } else console.log('ok  ', f); }
} else if (cmd === 'bin') {
  const out = rest[0]; fs.mkdirSync(out, { recursive: true }); const names = [];
  for (const f of rest.slice(1)) {
    const c = W.compile(JSON.parse(fs.readFileSync(f, 'utf8')));
    if (!c.ok) { bad++; console.log('FAIL', f, c.errors.join('; ')); continue; }
    fs.writeFileSync(path.join(out, path.basename(f, '.json') + '.nwl'), Buffer.from(c.bytes)); names.push(path.basename(f, '.json'));
    console.log('bin ', f, c.bytes.length + ' bytes');
  }
  fs.writeFileSync(path.join(out, 'list.txt'), names.join('\n') + '\n');
} else if (cmd === 'header') {                                       // node tools/widget_cli.js header src/DefaultLayout.h file.json
  const c = W.compile(JSON.parse(fs.readFileSync(rest[1], 'utf8')));
  if (!c.ok) { console.log('FAIL', rest[1], c.errors.join('; ')); process.exit(1); }
  let t = '#pragma once\n// Generated by tools/widget_cli.js from ' + rest[1].replace(/\\/g, '/') + ' - do not edit by hand.\n// The built-in dashboard: used until a layout is installed from the app, and by "restore standard design".\n#include <stddef.h>\n#include <stdint.h>\nstatic const uint8_t kDefaultLayout[] = {';
  const b = Array.from(c.bytes); b.forEach((v, i) => { t += (i % 16 === 0 ? '\n  ' : ' ') + '0x' + ('0' + v.toString(16)).slice(-2).toUpperCase() + ','; });
  t += '\n};\nstatic const size_t kDefaultLayoutLen = sizeof(kDefaultLayout);\n';
  fs.writeFileSync(rest[0], t);
  console.log('header', rest[0], b.length + ' bytes');
} else { console.log('usage: check|bin|header'); bad = 1; }
process.exit(bad ? 1 : 0);
